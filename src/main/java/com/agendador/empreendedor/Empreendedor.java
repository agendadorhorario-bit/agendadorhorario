package com.agendador.empreendedor;

public class Empreendedor {
    private Long idEmpreendedor;
    private String nomeEmpreendedor;
    private String enderecoEmpreendedor;
    private String celularEmpreendedor;
    private String usuarioEmpreendedor;
    private String senhaEmpreendedor;

    public Long getIdEmpreendedor() {
        return idEmpreendedor;
    }

    public void setIdEmpreendedor(Long idEmpreendedor) {
        this.idEmpreendedor = idEmpreendedor;
    }

    public String getNomeEmpreendedor() {
        return nomeEmpreendedor;
    }

    public void setNomeEmpreendedor(String nomeEmpreendedor) {
        this.nomeEmpreendedor = nomeEmpreendedor;
    }

    public String getEnderecoEmpreendedor() {
        return enderecoEmpreendedor;
    }

    public void setEnderecoEmpreendedor(String enderecoEmpreendedor) {
        this.enderecoEmpreendedor = enderecoEmpreendedor;
    }

    public String getCelularEmpreendedor() {
        return celularEmpreendedor;
    }

    public void setCelularEmpreendedor(String celularEmpreendedor) {
        this.celularEmpreendedor = celularEmpreendedor;
    }

    public String getUsuarioEmpreendedor() {
        return usuarioEmpreendedor;
    }

    public void setUsuarioEmpreendedor(String usuarioEmpreendedor) {
        this.usuarioEmpreendedor = usuarioEmpreendedor;
    }

    public String getSenhaEmpreendedor() {
        return senhaEmpreendedor;
    }

    public void setSenhaEmpreendedor(String senhaEmpreendedor) {
        this.senhaEmpreendedor = senhaEmpreendedor;
    }
}

